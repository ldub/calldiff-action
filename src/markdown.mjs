export const COMMENT_MARKER = '<!-- calldiff-action:sticky-comment -->'

export function sanitizeUntrustedText(value) {
  return String(value)
    .replaceAll('\r\n', '\n')
    .replaceAll('\r', '\n')
    .replace(/[\u001B\u009B][[\]()#;?]*(?:(?:(?:[a-zA-Z\d]*(?:;[-a-zA-Z\d\/#&.:=?%@~_]+)*)?\u0007)|(?:(?:\d{1,4}(?:[;:]\d{0,4})*)?[\dA-PR-TZcf-nq-uy=><~]))/g, '')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]/g, '')
}

export function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}

function fenceFor(value) {
  let longest = 0
  for (const match of value.matchAll(/`+/g)) longest = Math.max(longest, match[0].length)
  return '`'.repeat(Math.max(4, longest + 1))
}

function fenced(value, language = '') {
  const fence = fenceFor(value)
  return `${fence}${language}\n${value}\n${fence}`
}

function workflowRunUrl({ serverUrl, repository, runId }) {
  if (!serverUrl || !repository || !runId) return ''
  return `${serverUrl}/${repository}/actions/runs/${runId}`
}

function render({
  header,
  result,
  warnings,
  status,
  version,
  baseRef,
  headRef,
  truncated,
  serverUrl,
  repository,
  runId,
}) {
  const lines = [COMMENT_MARKER, header, '']
  const comparison = `${escapeHtml(baseRef)} → ${escapeHtml(headRef)}`
  lines.push(`Compared <code>${comparison}</code> with <code>calldiff ${escapeHtml(version || 'unknown')}</code>.`, '')

  if (status === 'error') {
    lines.push('> [!CAUTION]', '> calldiff could not complete. See the result below and the workflow logs.', '')
  } else if (warnings) {
    lines.push('> [!WARNING]', '> calldiff emitted warnings. The analysis may be incomplete.', '')
  }

  lines.push(fenced(result || '(calldiff produced no output)', 'diff'))

  if (warnings) {
    lines.push('', '<details>', '<summary>Warnings</summary>', '', fenced(warnings), '', '</details>')
  }

  if (truncated) {
    lines.push('', '> The displayed result was truncated. The complete result remains in the action result file for later steps in this job.')
  }

  const runUrl = workflowRunUrl({ serverUrl, repository, runId })
  const links = ['[calldiff](https://github.com/ldub/calldiff-action)']
  if (runUrl) links.push(`[workflow run](${runUrl})`)
  lines.push('', `<sub>Generated by ${links.join(' · ')}</sub>`)
  return lines.join('\n')
}

export function formatComment(options) {
  const safeResult = sanitizeUntrustedText(options.result)
  const safeWarnings = sanitizeUntrustedText(options.warnings)
  const warningsLimit = Math.min(8_000, Math.floor(options.maxLength / 4))
  const warnings = Buffer.byteLength(safeWarnings, 'utf8') > warningsLimit
    ? `${truncateUtf8(safeWarnings, warningsLimit)}\n… warnings truncated …`
    : safeWarnings

  const initial = render({ ...options, result: safeResult, warnings, truncated: false })
  if (Buffer.byteLength(initial, 'utf8') <= options.maxLength) return { body: initial, truncated: false }

  const empty = render({ ...options, result: '', warnings, truncated: true })
  let budget = Math.max(0, options.maxLength - Buffer.byteLength(empty, 'utf8'))
  let result = truncateUtf8(safeResult, budget)
  let body = render({ ...options, result: `${result}\n… result truncated …`, warnings, truncated: true })

  while (Buffer.byteLength(body, 'utf8') > options.maxLength && result.length > 0) {
    const overflow = Buffer.byteLength(body, 'utf8') - options.maxLength
    result = truncateUtf8(result, Math.max(0, Buffer.byteLength(result, 'utf8') - overflow - 4))
    body = render({ ...options, result: `${result}\n… result truncated …`, warnings, truncated: true })
  }

  return { body, truncated: true }
}

export function truncateUtf8(value, maxBytes) {
  if (Buffer.byteLength(value, 'utf8') <= maxBytes) return value
  let low = 0
  let high = value.length
  while (low < high) {
    const midpoint = Math.ceil((low + high) / 2)
    if (Buffer.byteLength(value.slice(0, midpoint), 'utf8') <= maxBytes) low = midpoint
    else high = midpoint - 1
  }
  const result = value.slice(0, low)
  return /[\uD800-\uDBFF]$/.test(result) ? result.slice(0, -1) : result
}
